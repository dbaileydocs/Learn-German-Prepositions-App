const AKK_ART: Record<Gender, ArticleOption> = { m: 'den', f: 'die', n: 'das', p: 'die' };
const DAT_ART: Record<Gender, ArticleOption> = { m: 'dem', f: 'der', n: 'dem', p: 'den' };
const NOM_ART: Record<Gender, ArticleOption> = { m: 'der', f: 'die', n: 'das', p: 'die' };
const GENDER_LABEL: Record<Gender, string> = {
  m: 'Masculine (der)',
  f: 'Feminine (die)',
  n: 'Neuter (das)',
  p: 'Plural (die)',
};

const CONTRACTION_NOTES: Record<string, string> = {
  'in|dem': 'Note: "in dem" commonly contracts to "im".',
  'in|das': 'Note: "in das" commonly contracts to "ins".',
  'an|dem': 'Note: "an dem" commonly contracts to "am".',
  'an|das': 'Note: "an das" commonly contracts to "ans".',
  'zu|dem': 'Note: "zu dem" commonly contracts to "zum".',
  'zu|der': 'Note: "zu der" commonly contracts to "zur".',
  'bei|dem': 'Note: "bei dem" commonly contracts to "beim".',
  'von|dem': 'Note: "von dem" commonly contracts to "vom".',
  'auf|das': 'Note: "auf das" commonly contracts to "aufs".',
  'für|das': 'Note: "für das" commonly contracts to "fürs".',
  'durch|das': 'Note: "durch das" commonly contracts to "durchs".',
  'um|das': 'Note: "um das" commonly contracts to "ums".',
};

export function seededShuffle<T>(arr: T[], seed: number): T[] {
  const copy = arr.slice();
  let s = seed >>> 0;
  for (let i = copy.length - 1; i > 0; i--) {
    s = (s * 1664525 + 1013904223) >>> 0;
    const j = s % (i + 1);
    const tmp = copy[i];
    copy[i] = copy[j];
    copy[j] = tmp;
  }
  return copy;
}

export function buildQuestionBank(): Question[] {
  const buckets: Record<FrameCategory, Omit<Question, 'id'>[]> = {
    akk: [],
    dat: [],
    wech_akk: [],
    wech_dat: [],
  };

  FRAMES.forEach((f) => {
    const isDat = f.cat === 'dat' || f.cat === 'wech_dat';
    const caseName: 'Akkusativ' | 'Dativ' = isDat ? 'Dativ' : 'Akkusativ';
    const catGroup = f.cat === 'wech_akk' || f.cat === 'wech_dat' ? 'wech' : f.cat;

    f.subjs.forEach(([sDe, sEn]) => {
      f.nouns.forEach((nKey) => {
        const noun = NOUNS[nKey];
        if (!noun) return;
        const art = isDat ? DAT_ART[noun.g] : AKK_ART[noun.g];
        const nounDisplay = isDat && noun.g === 'p' && noun.datPl ? noun.datPl : noun.de;
        const contraction = CONTRACTION_NOTES[`${f.prep}|${art}`] || '';
        const plNote = isDat && noun.g === 'p' ? ' Dativ plural adds -n to most nouns.' : '';

        buckets[f.cat].push({
          cat: catGroup,
          subCat: f.cat,
          caseName,
          prep: f.prep,
          beforeBlank: `${sDe} ${f.midDe}`,
          afterBlank: `${nounDisplay}${f.endDe}`,
          en: `${sEn} ${f.midEn} ${noun.en}.`,
          answer: art,
          nounDe: `${NOM_ART[noun.g]} ${noun.de}`,
          genderLabel: GENDER_LABEL[noun.g],
          explanation: `${f.why} "${noun.de}" is ${GENDER_LABEL[noun.g]}, which becomes "${art} ${nounDisplay}" in ${caseName}.${plNote}${contraction ? ` ${contraction}` : ''}`,
        });
      });
    });
  });

  const akkPicked = seededShuffle(buckets.akk, 101).slice(0, 300);
  const datPicked = seededShuffle(buckets.dat, 202).slice(0, 350);
  const wAkkPicked = seededShuffle(buckets.wech_akk, 303).slice(0, 175);
  const wDatPicked = seededShuffle(buckets.wech_dat, 404).slice(0, 175);

  const combined = seededShuffle(
    akkPicked.concat(datPicked, wAkkPicked, wDatPicked),
    909,
  );

  return combined.map((q, idx) => ({ id: idx + 1, ...q }));
}

export const ALL_QUESTIONS: Question[] = buildQuestionBank();

export const ALL_PREPOSITIONS: string[] = Array.from(
  new Set(ALL_QUESTIONS.map((q) => q.prep)),
).sort((a, b) => a.localeCompare(b, 'de'));
